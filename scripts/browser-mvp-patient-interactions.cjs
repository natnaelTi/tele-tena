// Explicitly invoked local synthetic review journey; real APIs, no transport mocks.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const site = process.env.TELE_TENA_REVIEW_SITE_PATH;
assert.ok(site && path.basename(site) === 'tele-tena-pr12-fresh.localhost');
const origin = 'http://127.0.0.1:8017';
const seed = JSON.parse(fs.readFileSync(path.join(site, 'private/tele_tena_review_seed.json')));
const credentials = JSON.parse(fs.readFileSync(path.join(site, 'private/tele_tena_review_accounts.json')));
let stage = 'launch';
(async () => {
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    page.setDefaultTimeout(12000);
    await page.goto(origin + '/teletena/sign-in');
    await page.getByRole('button', { name: 'Use email instead', exact: true }).click();
    await page.getByRole('button', { name: 'Use password instead', exact: true }).click();
    await page.getByLabel('Email', { exact: true }).fill(seed.users.patient);
    await page.getByLabel('Password', { exact: true }).fill(credentials[seed.users.patient]);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await page.getByRole('button', { name: 'Sign out', exact: true }).waitFor();
    const wallet = () => page.evaluate(async () => (await (await fetch('/api/method/tele_tena.api.journey.wallet', { cache: 'no-store' })).json()).message);
    stage = 'wallet validation';
    await page.goto(origin + '/teletena/patient/payments');
    const before = await wallet();
    await page.getByRole('button', { name: 'Add funds', exact: true }).click();
    let dialog = page.getByRole('dialog');
    await dialog.getByLabel('Amount (ETB)').fill('-1');
    await dialog.getByRole('button', { name: 'Add funds', exact: true }).click();
    await dialog.getByText('Enter a positive amount with at most two decimal places.', { exact: true }).waitFor();
    assert.deepEqual(await wallet(), before);
    stage = 'exact-amount funding';
    await dialog.getByLabel('Amount (ETB)').fill('25.50');
    await dialog.getByRole('button', { name: 'Add funds', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    const after = await wallet();
    assert.equal(after.available - before.available, 2550);
    assert.equal(after.reserved, before.reserved);
    await page.reload();
    assert.equal((await wallet()).available, after.available);
    stage = 'request composer validation and back';
    await page.goto(origin + '/teletena/patient/requests');
    const composer = page.locator('#request-composer');
    await composer.getByRole('button', { name: 'Continue', exact: true }).click();
    await composer.getByText('Describe the support you’re looking for.', { exact: true }).waitFor();
    const narrative = 'I would like support with managing everyday stress and finding a calmer routine.';
    await composer.locator('textarea').fill(narrative);
    await composer.getByRole('button', { name: 'Continue', exact: true }).click();
    await composer.getByLabel('Suggested service category').selectOption({ index: 1 });
    await composer.getByLabel('When would you like care?').selectOption('scheduled');
    await composer.getByRole('button', { name: 'Review privacy', exact: true }).click();
    await composer.getByText('Choose an earliest time.', { exact: true }).waitFor();
    await composer.getByLabel('When would you like care?').selectOption('immediate');
    await composer.getByRole('button', { name: 'Review privacy', exact: true }).click();
    await composer.locator('.disclosure-preview').waitFor();
    await composer.getByRole('button', { name: 'Back', exact: true }).click();
    await composer.getByRole('button', { name: 'Back', exact: true }).click();
    assert.equal(await composer.locator('textarea').inputValue(), narrative);
    stage = 'dialog close placement and focus';
    await page.goto(origin + '/teletena/patient/discovery');
    const trigger = page.getByRole('button', { name: 'View profile', exact: true }).first();
    await trigger.click();
    dialog = page.getByRole('dialog');
    await dialog.getByRole('link', { name: 'View full profile', exact: true }).waitFor();
    const bounds = await dialog.boundingBox();
    const close = await dialog.getByRole('button', { name: 'Close dialog', exact: true }).boundingBox();
    assert.ok(close.x > bounds.x + bounds.width / 2 && close.y < bounds.y + 80);
    await page.keyboard.press('Escape');
    await dialog.waitFor({ state: 'hidden' });
    assert.equal(await trigger.evaluate(element => element === document.activeElement), true);
    console.log('PASS: invalid funding leaves balances unchanged; exact funding persists; guided request validation/back/privacy; dialog close placement and focus return. Demonstration deposit retained.');
  } catch (error) {
    console.error('FAIL: ' + stage + ' (' + error.name + '); private details withheld.');
    process.exitCode = 1;
  } finally { await browser.close(); }
})();
